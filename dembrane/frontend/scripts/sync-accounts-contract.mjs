#!/usr/bin/env node
// Copies the accounts API contract and its demo fixtures from the platform package into
// the frontend, so both sides build against one source (platform/packages/accounts).
//
// Why a copy and not an import: the image build, Vercel and CI's frontend job install only
// dembrane/frontend, so a path into ../platform would not resolve its zod there. The copy
// imports zod through the `zod4` alias (npm:zod@4, the version the platform locks), which
// leaves the portal's own zod 3 untouched.
//
//   node scripts/sync-accounts-contract.mjs          write the copies
//   node scripts/sync-accounts-contract.mjs --check  fail when they drifted (CI)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, "../../platform/packages/accounts/src");
const target = path.resolve(here, "../src/features/accounts/contract");

const header = (name) =>
	`// Generated by scripts/sync-accounts-contract.mjs from platform/packages/accounts/src/${name}.ts.\n// Do not edit: change the platform file and run the script.\n`;

const files = ["contract", "fixtures"];
const check = process.argv.includes("--check");
let drifted = false;

mkdirSync(target, { recursive: true });
for (const name of files) {
	const raw = readFileSync(path.join(source, `${name}.ts`), "utf8");
	const out =
		header(name) +
		raw
			.replace(/from "zod";/g, 'from "zod4";')
			.replace(/from "\.\/contract";/g, 'from "./contract.gen";');
	const file = path.join(target, `${name}.gen.ts`);
	let current = null;
	try {
		current = readFileSync(file, "utf8");
	} catch {}
	if (current === out) continue;
	if (check) {
		console.error(`${path.relative(process.cwd(), file)} is out of date.`);
		drifted = true;
	} else {
		writeFileSync(file, out);
		console.log(`wrote ${path.relative(process.cwd(), file)}`);
	}
}

if (drifted) {
	console.error(
		"The accounts contract changed in platform/packages/accounts. Run: node scripts/sync-accounts-contract.mjs",
	);
	process.exit(1);
}
