#!/usr/bin/env node
// Copies the platform's error catalog (platform/packages/core/src/catalog) into the
// frontend, so the error presenter is typed against the codes the API sends: a code
// without a friendly message fails `tsc`, and so does a message for a code that is gone.
//
// Why a copy and not an import: CI's frontend job and the image build install only
// echo/frontend (see sync-accounts-contract.mjs). The copy is imported for types only, so
// none of it reaches a bundle.
//
//   node scripts/sync-error-codes.mjs          write the copies
//   node scripts/sync-error-codes.mjs --check  fail when they drifted (CI)
import {
	mkdirSync,
	readdirSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, "../../platform/packages/core/src/catalog");
const target = path.resolve(here, "../src/lib/errors/catalog");
const check = process.argv.includes("--check");

const header = (name) =>
	`// Generated by scripts/sync-error-codes.mjs from platform/packages/core/src/catalog/${name}.ts.\n// Do not edit: change the platform file and run the script.\n`;

mkdirSync(target, { recursive: true });
const wanted = new Map();
for (const file of readdirSync(source).filter((f) => f.endsWith(".ts"))) {
	const name = file.slice(0, -3);
	const raw = readFileSync(path.join(source, file), "utf8");
	wanted.set(
		`${name}.gen.ts`,
		header(name) + raw.replace(/from "\.\/([a-z_]+)";/g, 'from "./$1.gen";'),
	);
}

let drifted = false;
const existing = readdirSync(target).filter((f) => f.endsWith(".gen.ts"));
for (const file of existing) {
	if (wanted.has(file)) continue;
	if (check) {
		console.error(`src/lib/errors/catalog/${file} has no platform source.`);
		drifted = true;
	} else {
		rmSync(path.join(target, file));
		console.log(`removed src/lib/errors/catalog/${file}`);
	}
}
for (const [file, out] of wanted) {
	let current = null;
	try {
		current = readFileSync(path.join(target, file), "utf8");
	} catch {}
	if (current === out) continue;
	if (check) {
		console.error(`src/lib/errors/catalog/${file} is out of date.`);
		drifted = true;
	} else {
		writeFileSync(path.join(target, file), out);
		console.log(`wrote src/lib/errors/catalog/${file}`);
	}
}

if (drifted) {
	console.error(
		"The error catalog changed in platform/packages/core. Run: node scripts/sync-error-codes.mjs",
	);
	process.exit(1);
}
